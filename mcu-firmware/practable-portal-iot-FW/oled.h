void run_screen_num(screenState_t screen = POWER) {
  if (screen == POWER) {
    power_stats_screen();
  } else if (screen == NETWORK) {
    rpi_network_screen();
  } else if (screen == STATS) {
    rpi_stats_screen();
  } else {
    power_stats_screen();
    Serial.println("Error in screen state machine");
  }
}


void screen_timer(screenState_t screen = POWER) {
  if (screen == POWER) {
    if (millis() - screen_change_mS >= POWER_DISP_TIME_mS) {
      currentScreen = NETWORK;
      screen_change_mS = millis();
    }
  } else if (screen == NETWORK) {
    if (millis() - screen_change_mS >= NETWORK_DISP_TIME_mS) {
      currentScreen = STATS;
      screen_change_mS = millis();
    }
  } else if (screen == STATS) {
    if (millis() - screen_change_mS >= STATS_DISP_TIME_mS) {
      currentScreen = POWER;
      screen_change_mS = millis();
    }
  } else {
    currentScreen = POWER;
    Serial.println("Error in screen timer");
  }
}


